También conviene saber que el impacto de los automóviles en el medio ambiente no se limita a los gases de escape:
\begin{itemize}
	\item La contaminación acústica afecta negativamente a las poblaciones animales (incluidos los humanos) que viven cerca de las carreteras. Fíjate cómo el canto de los pájaros se vuelve más escaso cuando te acercas a una carretera.
	\item La fricción de los neumáticos con el asfalto libera partículas microscópicas al aire que pueden irritar las vías respiratorias.
	\item El desgaste de los frenos también contribuye a la contaminación atmosférica con sustancias nocivas que pueden llegar a los pulmones.
	\item Las sales esparcidas en las carreteras en invierno se filtran hacia las aguas subterráneas y afectan a los organismos que las consumen.
	\item El asfalto cubre el suelo como una tapa e impide la recarga de las reservas de aguas subterráneas.
	\item Las carreteras fragmentan el hábitat de los animales; a veces los animales que intentan cruzarlas son atropellados.
	\item Las carreteras asfaltadas contribuyen al efecto de ``isla de calor urbana'': el asfalto se calienta más que la tierra y por la noche irradia ese calor de vuelta a la atmósfera. Así, la temperatura media en las ciudades es más alta que en las zonas rurales.
\end{itemize}

\textbf{Soluciones y alternativas:}
\begin{itemize}
	\item Los automóviles eléctricos utilizan principalmente ``frenos regenerativos'' en lugar de frenos de fricción, eliminando así una de las fuentes de partículas finas en la atmósfera.
	\item El transporte sobre raíles (por ejemplo, tranvía, metro) elimina el efecto de la fricción neumático-asfalto; la fricción metal sobre metal es mucho menor, por lo que se consume menos energía para mover un tren.
	\item Los trenes de levitación magnética (Maglev) no tienen contacto alguno con el carril, lo que reduce aún más tanto la contaminación acústica como la resistencia al avance, haciendo este medio de transporte todavía más eficiente.
	\item Las vías férreas son permeables, es decir, no tienen el efecto de ``tapa'', a diferencia de las carreteras asfaltadas.
	\item Las vías férreas utilizan el espacio de forma mucho más eficiente: en la misma unidad de tiempo un tren transporta cientos de personas, mientras que en un automóvil caben solo unas pocas.
\end{itemize}

