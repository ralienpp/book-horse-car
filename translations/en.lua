  parent_guide_body  = [[\textbf{Sustainability} is the use of natural resources in a way that does not lead to their depletion or to the degradation of the environment. Overexploiting resources does not always produce immediately visible consequences, so the excess becomes apparent later, sometimes -- too late.

The impact of cars on the environment is not limited to exhaust fumes:
\begin{itemize}
	\item Noise pollution negatively affects the animal populations (humans included) living near roads. Notice how birdsong grows scarcer as you approach a road.
	\item The friction of tyres against the road releases microscopic particles into the air; these can irritate the airways.
	\item Brake wear also contributes to atmospheric pollution with harmful substances that can reach the lungs.
	\item Salts spread on roads in winter then seep into the groundwater and affect the organisms that consume this water.
	\item Paved roads cover the ground like a lid and prevent the replenishment of groundwater reserves.
	\item Roads cause the fragmentation of animal habitats; and sometimes animals that venture to cross the road are struck by cars.
	\item Paved roads contribute to the ``urban heat island'' effect -- asphalt heats up more than soil, and at night this heat is radiated back into the atmosphere. Thus the average temperature in cities is higher than in rural areas.
\end{itemize}

\textbf{Solutions and alternatives:}
\begin{itemize}
	\item Electric cars mostly use ``regenerative brakes'' rather than friction brakes. This replacement removes one of the sources of tiny particles that reach the atmosphere.
	\item Rail transport (e.g. tram, metro) eliminates the effect of wheel-on-asphalt friction; metal-on-metal friction is much smaller, so less energy is consumed to set a train in motion.
	\item Magnetic-levitation trains (Maglev) have no contact at all with the rail, which further reduces both noise pollution and frictional force. The efficiency of this means of transport is therefore even greater.
	\item Railways are permeable, that is, they have no ``lid'' effect, unlike paved roads.
	\item Railways use space far more efficiently -- in the same span of time a train carries hundreds of people, whereas only a few fit in a car.
\end{itemize}

\textbf{Why is it important to vote?}
A large part of the problems we face are not inevitable tragedies we were fated to endure, but a consequence of poor management driven by the incompetence or corruption of the administration. In a democracy the administration can be changed through elections. Voting is therefore one of the instruments at our disposal, and it is important to use it. \emph{Rationally}!

The book ``Climate Injustice'' by Friederike Otto describes many cases in which regions with populations in the millions go through droughts or floods that could have been avoided had the administration correctly applied solutions proposed by researchers.

Although the problems that could have been avoided were not avoided -- we must focus on those that \emph{can still be avoided}.

\textbf{The power of a single person} is limited. Even if you cycle your whole life, industrial-scale pollution eclipses your personal effort. And yet none of us is alone -- \emph{cooperation brings change}. We can cooperate by voting for more reasonable policies, by developing new technologies, and so on.

