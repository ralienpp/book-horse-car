Gran parte delle problematiche con cui ci confrontiamo non sono tragedie inevitabili a cui siamo condannati per destino, bensì la diretta conseguenza di una cattiva gestione, dettata dall'incompetenza o dalla corruzione dell'amministrazione pubblica. In una democrazia l'amministrazione si può cambiare per mezzo del voto. Pertanto, la scheda elettorale è uno degli strumenti a nostra disposizione, ed è fondamentale servirsene. \emph{Con criterio}!

