	\item Асфальтированные дороги способствуют эффекту ``городского острова тепла'' -- асфальт нагревается сильнее, чем земля, и ночью это тепло излучается обратно в атмосферу. Так средняя температура в городах выше, чем в сельской местности.
\end{itemize}

\textbf{Решения и альтернативы:}
\begin{itemize}
	\item Электромобили преимущественно используют ``рекуперативное торможение'', а не фрикционные тормоза. Эта замена устраняет один из источников мельчайших частиц, попадающих в атмосферу.
	\item Рельсовый транспорт (например, трамвай, метро) устраняет эффект трения колеса об асфальт; трение металла о металл намного меньше, поэтому меньше энергии тратится на то, чтобы сдвинуть поезд с места.
	\item Поезда на магнитной подушке (Maglev) вообще не имеют контакта с рельсом, что ещё больше снижает и шумовое загрязнение, и силу трения. Поэтому КПД этого вида транспорта ещё выше.
	\item Железные дороги проницаемы, то есть не имеют эффекта ``крышки'', в отличие от асфальтированных дорог.
	\item Железные дороги используют пространство гораздо эффективнее -- за одно и то же время поезд перевозит сотни людей, тогда как в автомобиль помещается лишь несколько человек.
\end{itemize}

\textbf{Почему важно голосовать?}
Значительная часть проблем, с которыми мы сталкиваемся, — это не неизбежные трагедии, которые нам суждено терпеть, а следствие плохого управления, вызванного некомпетентностью или коррупцией администрации. В демократии администрацию можно сменить через выборы. Поэтому голос — один из инструментов, имеющихся в нашем распоряжении, и его важно использовать. \emph{Рационально}!

Книга ``Climate Injustice'' Фридерике Отто описывает множество случаев, когда регионы с населением в миллионы человек переживают засухи или наводнения, которых можно было бы избежать, если бы администрация правильно применила решения, предложенные учёными.

Хотя проблемы, которых можно было избежать, не были предотвращены -- мы должны сосредоточиться на тех, которых \emph{ещё можно избежать}.

\textbf{Сила одного человека} ограничена. Даже если ты будешь ездить на велосипеде всю жизнь, загрязнение в промышленных масштабах затмевает твои личные усилия. И всё же никто из нас не одинок -- \emph{сотрудничество приносит перемены}. Мы можем сотрудничать, голосуя за более разумную политику, разрабатывая новые технологии и так далее.

