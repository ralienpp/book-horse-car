\textbf{वोट करना क्यों ज़रूरी है?}
हम जिन समस्याओं का सामना करते हैं उनमें से अधिकांश अपरिहार्य त्रासदियाँ नहीं हैं जिन्हें हमें झेलना ही है -- बल्कि ये प्रशासन की अक्षमता या भ्रष्टाचार से उपजी कुप्रबंधन की देन हैं। लोकतंत्र में चुनावों के ज़रिए प्रशासन बदला जा सकता है। इसलिए वोट उन साधनों में से एक है जो हमारे पास हैं, और इसका उपयोग करना ज़रूरी है। \emph{सोच-समझकर}!

फ्रीडेरिके ओटो की किताब ``Climate injustice'' में ऐसे कई मामलों का वर्णन है जहाँ करोड़ों की आबादी वाले क्षेत्र सूखे या बाढ़ से गुज़रे, जिन्हें टाला जा सकता था अगर प्रशासन ने शोधकर्ताओं के सुझाए समाधानों को सही तरीके से लागू किया होता।

हालाँकि जो समस्याएँ टाली जा सकती थीं वे नहीं टाली गईं -- फिर भी हमें उन पर ध्यान केंद्रित करना चाहिए जो \emph{अभी भी टाली जा सकती हैं}।

\textbf{एक अकेले इंसान की ताक़त} सीमित है। भले ही आप जीवन भर साइकिल चलाएँ, औद्योगिक स्तर का प्रदूषण आपके व्यक्तिगत प्रयास को ढक लेता है। फिर भी, हम में से कोई अकेला नहीं है -- \emph{सहयोग ही बदलाव लाता है}। हम अधिक उचित नीतियों के पक्ष में वोट करके, नई तकनीकें विकसित करके सहयोग कर सकते हैं।

\textbf{गैर-विनियमित साझा संसाधनों की त्रासदी} (Tragedy of the Commons) मानव समाज के कई पहलुओं में देखी जा सकती है। त्रासदी इस बात में निहित है कि यदि किसी साझा संसाधन का दुरुपयोग किया जाता है, तो अक्सर उस दुरुपयोग के परिणाम और सुधार की लागत समाज द्वारा वहन की जाती है, न कि दुरुपयोग करने वाले व्यक्ति द्वारा। अर्थशास्त्री इस घटना को \emph{``नकारात्मक बाह्यता''} (negative externality) कहते हैं।
एक चरागाह की कल्पना करें, जहाँ चरवाहे अपनी भेड़ों को चराने के लिए दिन में एक घंटा लाते हैं। जानवर चले जाते हैं, और अगले झुंड के आने तक घास फिर से उग आती है, जिससे सभी की भेड़ें तृप्त रहती हैं। लेकिन एक चरवाहा अपनी भेड़ों को आधा घंटा अधिक चराने का निर्णय लेता है। उसकी भेड़ें अधिक घास खाएंगी और अधिक दूध देंगी (यानी व्यक्तिगत लाभ)। लेकिन यह उन झुंडों के नुकसान पर होता है जो बाद में आते हैं — चरागाह को पुनर्जीवित होने के लिए कम समय मिलता है, जिसके परिणामस्वरूप अन्य जानवर कम खा पाते हैं (अर्थात नुकसान का बाह्यीकरण कर दिया गया है)। शुरुआत में यह अंतर नगण्य लगेगा।
लेकिन क्या होगा यदि हर कोई अपने झुंड को अधिक समय तक चराने का निर्णय ले ले? घास को फिर से पनपने का समय नहीं मिलेगा, अंततः चरागाह सूख जाएगा -- और अंत में किसी के पास कुछ नहीं बचेगा।
इस वर्णित स्थिति में केवल एक ही लाभार्थी है -- वह चालाक चरवाहा, जबकि बाकी सभी को नुकसान होता है। हालाँकि, पारिस्थितिकी तंत्र के नष्ट होने के साथ, उस ``लाभार्थी'' को भी अंततः कीमत चुकानी पड़ती है, भले ही वह बाकी लोगों की तुलना में कुछ समय बेहतर स्थिति में रहे।
साझा संसाधनों की त्रासदी का एक और रूप कभी-कभी दोस्तों के साथ रेस्तरां में देखा जा सकता है। यदि हम शुरू में ही यह तय कर लेते हैं कि बिल सभी में समान रूप से बांटा जाएगा, तो कोई ऐसा व्यक्ति हो सकता है जो अधिक महंगे व्यंजन और पेय ऑर्डर करे। चूंकि उनका भुगतान सभी में समान रूप से वितरित होगा, इसलिए उस व्यक्ति को दूसरों की ``सब्सिडी'' से लाभ होगा।
