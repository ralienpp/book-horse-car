\textbf{Varför är det viktigt att rösta?}
En stor del av de problem vi står inför är inte oundvikliga tragedier som vi är dömda att uthärda, utan en konsekvens av dåligt styre till följd av inkompetens eller korruption inom förvaltningen. I en demokrati kan styret bytas ut genom val. Därför är rösträtten ett av de verktyg vi har till vårt förfogande, och det är viktigt att vi använder den. \emph{Förståndigt}!

Boken ``Climate injustice'', skriven av Friederike Otto, beskriver ett flertal fall där regioner med miljontals invånare drabbas av torka eller översvämningar som hade kunnat undvikas om beslutsfattarna på rätt sätt hade tillämpat forskarnas föreslagna lösningar.

Även om problem som hade kunnat undvikas inte avvärjdes, måste vi fokusera på de problem som \emph{fortfarande kan undvikas}.


\textbf{En enskild människas kraft} är begränsad. Även om du skulle cykla hela livet överskuggar de industriella utsläppen dina personliga ansträngningar. Samtidigt är ingen av oss ensam -- \emph{samarbete skapar förändring}. Vi kan samarbeta genom att rösta för en mer förnuftig politik, utveckla ny teknik och så vidare.


\textbf{Allmänningens tragedi} i oreglerad form präglar många delar av det mänskliga samhället. Tragedin består i att när en gemensam resurs överutnyttjas får samhället ofta ta konsekvenserna och stå för saneringskostnaderna, inte den som orsakade skadan. Ekonomer kallar detta fenomen för en \emph{``negativ externalitet''}.

Föreställ dig en betesmark där herdarna låter sina får beta en timme om dagen. Djuren lämnar platsen, gräset hinner växa till sig tills nästa flock anländer och allas får blir mätta. Men tänk om en herde bestämmer sig för att låta sina får beta en halvtimme längre. Hans får äter mer gräs och ger mer mjölk (en personlig vinning). Detta sker dock på bekostnad av de flockar som kommer efter -- betesmarken får mindre tid på sig att återhämta sig och övriga djur får mindre mat (skadan vältras över på andra). Till en början är skillnaden knappt märkbar.
Men vad händer om alla bestämmer sig för att låta sina djur beta längre? Gräset hinner inte återhämta sig och i slutändan torkar betesmarken ut -- och alla står tomhänta.

