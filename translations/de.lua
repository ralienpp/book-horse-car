Die Auswirkungen von Autos auf die Umwelt beschränken sich nicht auf Abgase:
\begin{itemize}
	\item Lärmbelastung schadet den Tierpopulationen (Menschen eingeschlossen), die in der Nähe von Straßen leben. Achte darauf, wie der Vogelgesang seltener wird, je näher du einer Straße kommst.
	\item Die Reibung der Reifen auf der Straße setzt mikroskopische Partikel in die Luft frei; diese können die Atemwege reizen.
	\item Auch der Bremsenverschleiß trägt zur Luftverschmutzung mit schädlichen Stoffen bei, die in die Lunge gelangen können.
	\item Das im Winter auf die Straßen gestreute Salz sickert anschließend ins Grundwasser und schädigt die Organismen, die dieses Wasser aufnehmen.
	\item Asphaltierte Straßen bedecken den Boden wie ein Deckel und verhindern die Auffüllung der Grundwasservorräte.
	\item Straßen führen zur Zerschneidung von Tierlebensräumen; und manchmal werden Tiere, die es wagen, die Straße zu überqueren, von Autos erfasst.
	\item Asphaltierte Straßen tragen zum Effekt der ``städtischen Wärmeinsel'' bei -- Asphalt erhitzt sich stärker als Erde, und nachts wird diese Wärme in die Atmosphäre zurückgestrahlt. So ist die Durchschnittstemperatur in Städten höher als in ländlichen Gebieten.
\end{itemize}

\textbf{Lösungen und Alternativen:}
\begin{itemize}
	\item Elektroautos nutzen überwiegend ``regeneratives Bremsen'' statt Reibungsbremsen. Dieser Ersatz beseitigt eine der Quellen winziger Partikel, die in die Atmosphäre gelangen.
	\item Der schienengebundene Verkehr (z.\,B. Straßenbahn, U-Bahn) beseitigt den Effekt der Rad-auf-Asphalt-Reibung; die Metall-auf-Metall-Reibung ist viel geringer, sodass weniger Energie nötig ist, um einen Zug in Bewegung zu setzen.
	\item Magnetschwebebahnen (Maglev) haben überhaupt keinen Kontakt zur Schiene, was sowohl die Lärmbelastung als auch die Reibungskraft weiter verringert. Der Wirkungsgrad dieses Verkehrsmittels ist daher noch höher.
	\item Eisenbahnstrecken sind durchlässig, das heißt, sie haben keinen ``Deckel''-Effekt, anders als asphaltierte Straßen.
	\item Eisenbahnen nutzen den Raum weit effizienter -- in derselben Zeitspanne befördert ein Zug Hunderte von Menschen, während in ein Auto nur wenige passen.
\end{itemize}

\textbf{Warum ist es wichtig zu wählen?}
Ein großer Teil der Probleme, mit denen wir konfrontiert sind, sind keine unvermeidlichen Tragödien, die zu ertragen uns bestimmt war, sondern eine Folge schlechten Managements, bedingt durch Inkompetenz oder Korruption der Verwaltung. In einer Demokratie kann die Verwaltung durch Wahlen geändert werden. Die Stimme ist daher eines der Instrumente, die uns zur Verfügung stehen, und es ist wichtig, sie zu nutzen. \emph{Mit Verstand}!

Das Buch ``Climate Injustice'' von Friederike Otto beschreibt zahlreiche Fälle, in denen Regionen mit Millionen von Einwohnern Dürren oder Überschwemmungen durchmachen, die hätten vermieden werden können, wenn die Verwaltung die von Forschern vorgeschlagenen Lösungen richtig angewandt hätte.

Auch wenn die vermeidbaren Probleme nicht vermieden wurden -- müssen wir uns auf jene konzentrieren, die \emph{noch vermieden werden können}.

\textbf{Die Macht eines einzelnen Menschen} ist begrenzt. Selbst wenn du dein ganzes Leben lang Fahrrad fährst, stellt die Verschmutzung im industriellen Maßstab deinen persönlichen Einsatz in den Schatten. Dennoch ist keiner von uns allein -- \emph{Zusammenarbeit bringt Veränderung}. Wir können zusammenarbeiten, indem wir für vernünftigere Politik stimmen, indem wir neue Technologien entwickeln und so weiter.

