\end{itemize}

\textbf{வாக்களிப்பது ஏன் முக்கியம்?}
நாம் எதிர்கொள்ளும் பிரச்சினைகளில் பெரும்பாலானவை நாம் தாங்கியே ஆக வேண்டிய தவிர்க்க முடியாத சோகங்கள் அல்ல -- மாறாக, நிர்வாகத்தின் திறமையின்மை அல்லது ஊழலால் ஏற்படும் மோசமான மேலாண்மையின் விளைவு. ஒரு ஜனநாயகத்தில் தேர்தல்கள் மூலம் நிர்வாகத்தை மாற்றலாம். எனவே வாக்கு என்பது நம்மிடம் உள்ள கருவிகளில் ஒன்று -- அதை பயன்படுத்துவது முக்கியம். \emph{விவேகமாக}!

ஃப்ரீடெரிக்கே ஓட்டோவின் ``Climate injustice'' என்ற புத்தகம் பல வழக்குகளை விவரிக்கிறது -- கோடிக்கணக்கான மக்கள் வாழும் பகுதிகள் வறட்சி அல்லது வெள்ளத்தால் பாதிக்கப்பட்டன, ஆனால் நிர்வாகம் ஆராய்ச்சியாளர்கள் முன்மொழிந்த தீர்வுகளை சரியாக செயல்படுத்தியிருந்தால் இவை தவிர்க்கப்பட்டிருக்கலாம்.

தவிர்க்கப்பட்டிருக்கக்கூடிய பிரச்சினைகள் தவிர்க்கப்படவில்லை என்றாலும் -- \emph{இன்னும் தவிர்க்கக்கூடியவற்றில்} நாம் கவனம் செலுத்த வேண்டும்.

