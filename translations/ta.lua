	\item தண்டவாள போக்குவரத்து (எ.கா., தண்டவாளப் பேருந்து, நிலத்தடி ரயில்) சக்கரங்கள் தாரில் உராய்வதால் ஏற்படும் விளைவை நீக்குகிறது; உலோகம்-மீது-உலோகம் உராய்வு மிகவும் குறைவாக இருப்பதால் ஒரு ரயிலை நகர்த்த குறைவான ஆற்றல் மட்டுமே தேவைப்படுகிறது.
	\item காந்த மிதவை ரயில்கள் (Maglev) தண்டவாளத்துடன் எந்த தொடர்பும் இல்லாமல் இயங்குகின்றன, இது சத்த மாசுபாட்டையும் உராய்வு விசையையும் மேலும் குறைக்கிறது. இதனால் இந்த போக்குவரத்து முறையின் திறன் இன்னும் அதிகமாகிறது.
