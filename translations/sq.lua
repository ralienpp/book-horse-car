\textbf{Pse është e rëndësishme të votosh?}
Një pjesë e madhe e problemeve me të cilat përballemi nuk janë tragjedi të pashmangshme që na është caktuar t'i durojmë, por një pasojë e menaxhimit të keq, të përcaktuar nga paaftësia ose korrupsioni i administratës. Në një demokraci administrata mund të ndryshojë nëpërmjet zgjedhjeve. Prandaj, votimi është një nga instrumentet që kemi në dispozicion, dhe është e rëndësishme ta përdorim. \emph{Me arsye}!

Libri ``Climate injustice'', shkruar nga Friederike Otto, përshkruan raste të shumta në të cilat rajone me popullsi prej milionash kalojnë nëpër thatësira ose përmbytje, të cilat mund të ishin shmangur nëse administrata do të kishte zbatuar saktë zgjidhjet e propozuara nga studiuesit.

Edhe pse problemet që mund të ishin shmangur nuk u shmangën -- duhet të përqendrohemi në ato që \emph{ende mund të shmangohen}.

